/**
 * EstiMate CSV / Excel Exporter
 * Generates an Excel-compatible CSV Bill of Quantities with UTF-8 BOM,
 * structured according to Philippine Construction Quantity Surveying standards.
 */

function escapeCsvCell(cell) {
  if (cell === null || cell === undefined) return '""'
  const str = String(cell)
  if (str.includes('"') || str.includes(',') || str.includes('\n') || str.includes('\r')) {
    return `"${str.replace(/"/g, '""')}"`
  }
  return `"${str}"`
}

export function buildBOQCsv(project, meta = {}) {
  const lines = []

  const projectName = meta.name || 'Untitled Residential Project'
  const clientName = meta.client || 'Private Client'
  const location = meta.location || 'Philippines'
  const dateStr = new Date().toLocaleDateString('en-PH', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  })

  // 1. Header Information
  lines.push(['ESTIMATE PHILIPPINES - BILL OF QUANTITIES (BOQ) & COST ESTIMATE'].map(escapeCsvCell).join(','))
  lines.push(['Generated by EstiMate Pro Suite | DPWH & National Building Code Compliant'].map(escapeCsvCell).join(','))
  lines.push([])
  lines.push(['PROJECT DETAILS', ''].map(escapeCsvCell).join(','))
  lines.push(['Project Title:', projectName].map(escapeCsvCell).join(','))
  lines.push(['Client / Owner:', clientName].map(escapeCsvCell).join(','))
  lines.push(['Project Location:', location].map(escapeCsvCell).join(','))
  lines.push(['Date of Estimate:', dateStr].map(escapeCsvCell).join(','))
  lines.push([])

  // 2. Commercial Summary
  lines.push(['COMMERCIAL & CONTRACT SUMMARY', ''].map(escapeCsvCell).join(','))
  lines.push(['Direct Material Cost (PHP):', (project.materialCost || 0).toFixed(2)].map(escapeCsvCell).join(','))
  lines.push(['Direct Labor Cost (PHP):', (project.laborCost || 0).toFixed(2)].map(escapeCsvCell).join(','))
  lines.push(['Total Direct Cost (PHP):', (project.directCost || 0).toFixed(2)].map(escapeCsvCell).join(','))
  lines.push([`Overhead, Contingencies & Misc (OCM) (${project.ocmRate || 8}%):`, (project.ocmCost || 0).toFixed(2)].map(escapeCsvCell).join(','))
  lines.push([`Contractor's Profit (${project.profitRate || 10}%):`, (project.profitCost || 0).toFixed(2)].map(escapeCsvCell).join(','))
  lines.push([`Value Added Tax (VAT) (${project.taxRate || 5}%):`, (project.taxCost || 0).toFixed(2)].map(escapeCsvCell).join(','))
  lines.push(['TOTAL ORIGINAL CONTRACT / BID (PHP):', (project.originalContract || project.totalBid || 0).toFixed(2)].map(escapeCsvCell).join(','))
  
  if (project.approvedVOAmount !== undefined && project.approvedVOAmount !== 0) {
    lines.push(['Approved Variation Orders Net (PHP):', (project.approvedVOAmount || 0).toFixed(2)].map(escapeCsvCell).join(','))
    lines.push(['REVISED CONTRACT VALUE (PHP):', (project.revisedContract || project.totalBid || 0).toFixed(2)].map(escapeCsvCell).join(','))
  }
  
  lines.push(['15% Mobilization / Advance Payment (PHP):', (project.advancePayment || 0).toFixed(2)].map(escapeCsvCell).join(','))
  lines.push(['10% Retention Guarantee (PHP):', (project.retentionMoney || 0).toFixed(2)].map(escapeCsvCell).join(','))
  lines.push([])

  // 3. Itemized Schedule of Works
  lines.push(['SCHEDULE OF WORKS & DETAILED QUANTITIES'].map(escapeCsvCell).join(','))
  const tableHeaders = [
    'Item No.',
    'Trade / Scope',
    'Category',
    'Description',
    'Quantity',
    'Unit',
    'Unit Cost (PHP)',
    'Total Amount (PHP)',
  ]
  lines.push(tableHeaders.map(escapeCsvCell).join(','))

  if (Array.isArray(project.items) && project.items.length > 0) {
    project.items.forEach((item, index) => {
      lines.push([
        index + 1,
        item.module || 'General',
        item.category || 'General',
        item.name || '',
        (item.quantity || 0).toFixed(2),
        item.unit || '',
        (item.unitCost || 0).toFixed(2),
        (item.amount || 0).toFixed(2),
      ].map(escapeCsvCell).join(','))
    })
  }

  lines.push([])
  lines.push(['TOTAL DIRECT COST (PHP):', '', '', '', '', '', '', (project.directCost || 0).toFixed(2)].map(escapeCsvCell).join(','))
  lines.push([])

  // 4. Variation Orders Ledger (if any)
  if (Array.isArray(project.variationOrders) && project.variationOrders.length > 0) {
    lines.push(['VARIATION ORDER (VO) / CHANGE ORDER LEDGER'].map(escapeCsvCell).join(','))
    lines.push(['VO #', 'Description / Scope Change', 'Type', 'Status', 'Date Logged', 'Amount (PHP)'].map(escapeCsvCell).join(','))
    project.variationOrders.forEach((vo, idx) => {
      lines.push([
        vo.voNumber || `VO-${String(idx + 1).padStart(3, '0')}`,
        vo.description || '',
        vo.type || 'Additive',
        vo.status || 'Pending',
        vo.date || '',
        (Number(vo.amount) || 0).toFixed(2),
      ].map(escapeCsvCell).join(','))
    })
    lines.push([])
  }

  // Prepend UTF-8 Byte Order Mark (BOM) \uFEFF so Excel automatically parses UTF-8 encoding
  return '\uFEFF' + lines.join('\r\n')
}

export function exportBOQCsv(project, meta = {}) {
  const csvData = buildBOQCsv(project, meta)
  const blob = new Blob([csvData], { type: 'text/csv;charset=utf-8;' })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  const cleanName = (meta.name || 'EstiMate_BOQ').replace(/[^a-zA-Z0-9_-]/g, '_')
  link.setAttribute('href', url)
  link.setAttribute('download', `${cleanName}_${new Date().toISOString().slice(0, 10)}.csv`)
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
  URL.revokeObjectURL(url)
}
